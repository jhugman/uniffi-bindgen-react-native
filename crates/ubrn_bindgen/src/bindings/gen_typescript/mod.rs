#[derive(Template)]
#[template(syntax = "ts", escape = "none", path = "index.ts")]
struct IndexTsWrapper {
    modules: Vec<ModuleMetadata>,
    flavor: AbiFlavor,
    /// File stem of the module this index loads, which staging places
    /// alongside it. Empty for flavors that load no wasm.
    wasm_stem: String,
    /// Whether the module imports wasm-bindgen's placeholder namespace, in
    /// which case staging writes a `<stem>_bg.js` for us to import.
    has_wasm_bindgen_glue: bool,
    /// Drops the `@ts-nocheck` header; set only when every namespace opts in.
    strict_type_checking: bool,
    /// A namespace delivering over a port has a promise-returning
    /// `initialize()`, so the index awaits it.
    async_delivery: bool,
}

#[derive(Template)]
#[template(syntax = "ts", escape = "none", path = "player-definitions.ts")]
struct PlayerDefinitionsTsWrapper {
    modules: Vec<ModuleMetadata>,
    strict_type_checking: bool,
}

#[derive(Template)]
#[template(syntax = "ts", escape = "none", path = "index.port.ts")]
struct IndexPortTsWrapper {
    modules: Vec<ModuleMetadata>,
    strict_type_checking: bool,
}

/// Test-only entry point: render the `--async` index files for the given
/// namespaces, as [`generate_async_index_code`] names them.
#[doc(hidden)]
pub fn render_async_index_for_test(namespaces: &[&str]) -> Result<Vec<(&'static str, String)>> {
    let modules = namespaces
        .iter()
        .map(|ns| ModuleMetadata::new(ns))
        .collect();
    generate_async_index_code(modules, false)
}

/// Test-only entry point: render the player lowlevel TS wrapper for a
/// minimal `PlayerFfiModule` configured with the given flavor. Used by
/// integration tests to assert template branching without standing up a
/// full `general::Namespace`.
#[doc(hidden)]
pub fn render_player_lowlevel_for_test(
    flavor: &crate::AbiFlavor,
    async_delivery: bool,
) -> Result<String> {
    let module =
        ffi_module_player::PlayerFfiModule::minimal_for_test(flavor.clone(), async_delivery);
    generate_player_lowlevel_code(module)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stale_async_index_files_are_removed_but_the_apps_are_kept() -> Result<()> {
        let dir = camino::Utf8PathBuf::try_from(std::env::temp_dir())?
            .join(format!("ubrn-stale-async-index-{}", std::process::id()));
        std::fs::create_dir_all(&dir)?;
        let [definitions, port] = ASYNC_INDEX_FILES;
        std::fs::write(dir.join(definitions), format!("{GENERATED_HEADER} ubrn\n"))?;
        std::fs::write(dir.join(port), "// The app's own port entry.\n")?;

        remove_stale_async_index_files(&dir)?;
        // With nothing left to remove, a second run is a no-op.
        remove_stale_async_index_files(&dir)?;

        assert!(!dir.join(definitions).exists());
        assert!(dir.join(port).exists());
        std::fs::remove_dir_all(&dir)?;
        Ok(())
    }
}
