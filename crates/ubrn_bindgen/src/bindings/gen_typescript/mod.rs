pub(crate) fn generate_index_code(
    modules: Vec<ModuleMetadata>,
    flavor: AbiFlavor,
    wasm_stem: String,
    has_wasm_bindgen_glue: bool,
    strict_type_checking: bool,
    async_delivery: bool,
) -> Result<String> {
    IndexTsWrapper {
        modules,
        flavor,
        wasm_stem,
        has_wasm_bindgen_glue,
        strict_type_checking,
        async_delivery,
    }
    .render()
    .context("generating index.ts from IR failed")
}

/// The files a library under async delivery gets beside `index.ts`: its merged
/// table, and an entry that connects every namespace through one port. A
/// namespace is an identifier, so neither name can clash with one.
pub(crate) const ASYNC_INDEX_FILES: [&str; 2] = ["player-definitions.ts", "index.port.ts"];

/// How every TypeScript template starts, so a file the bindgen wrote can be told from the app's.
const GENERATED_HEADER: &str = "// This file was autogenerated by";

/// Removes the [`ASYNC_INDEX_FILES`] an earlier `--async` run left in `ts_dir`. A file of the
/// same name that does not start with the generated header is the app's, and stays.
pub(crate) fn remove_stale_async_index_files(ts_dir: &camino::Utf8Path) -> Result<()> {
    for name in ASYNC_INDEX_FILES {
        let path = ts_dir.join(name);
        let Ok(contents) = std::fs::read_to_string(&path) else {
            continue;
        };
        if contents.starts_with(GENERATED_HEADER) {
            std::fs::remove_file(&path)?;
        }
    }
    Ok(())
}

/// The [`ASYNC_INDEX_FILES`], by name.
pub(crate) fn generate_async_index_code(
    modules: Vec<ModuleMetadata>,
    strict_type_checking: bool,
) -> Result<Vec<(&'static str, String)>> {
    let definitions = PlayerDefinitionsTsWrapper {
        modules: modules.clone(),
        strict_type_checking,
    }
    .render()
    .context("generating player-definitions.ts failed")?;
    let port = IndexPortTsWrapper {
        modules,
        strict_type_checking,
    }
    .render()
    .context("generating index.port.ts failed")?;
    let [definitions_file, port_file] = ASYNC_INDEX_FILES;
    Ok(vec![(definitions_file, definitions), (port_file, port)])
}

